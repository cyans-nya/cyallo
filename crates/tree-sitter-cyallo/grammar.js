// Highlighting syntax follows cyallo-parser. This grammar deliberately accepts
// expression fragments and unfinished literals while a document is being edited.
const commaSep = rule => optional(seq(rule, repeat(seq(',', rule)), optional(',')));
module.exports = grammar({
  name: 'cyallo',
  extras: $ => [/\s/, $.comment],
  word: $ => $.identifier,
  conflicts: $ => [
    [$._expression, $.generic_call_expression, $.record_expression, $.typed_collection],
    [$.type_identifier, $._path_keyword],
    [$._type, $.reference_type],
    [$._type, $.generic_type],
    [$.arguments, $.tuple_expression],
    [$._expression, $.record_expression],
  ],
  rules: {
    source_file: $ => repeat(choice($._item, ';')),
    _item: $ => choice(
      $.attribute, $.function_declaration, $.record_declaration, $.enum_declaration,
      $.module_declaration, $.use_declaration, $.trait_declaration,
      $.impl_declaration, $.interface_implementation, $.world_declaration,
      $.property_declaration, $.type_declaration,
      $.variable_declaration, $.if_statement, $.while_statement,
      $.for_statement, $.return_statement, $.jump_statement,
      $.assignment_statement, $._expression,
    ),
    visibility: _ => seq('pub', optional(seq('(', 'crate', ')'))),
    attribute: $ => seq('#', '[', field('name', $.identifier), optional(seq('(', choice($.identifier, $.string), ')')), ']'),
    function_declaration: $ => prec.right(seq(optional($.visibility), choice('fn', 'proc'), field('name', $.identifier), optional($.generic_parameters), $.parameters, optional(seq('->', $._type)), optional(choice($.block, ';')))),
    parameters: $ => seq('(', commaSep($.parameter), ')'),
    parameter: $ => seq(optional('...'), optional('read'), field('name', $.identifier), optional(seq(':', $._type))),
    generic_parameters: $ => seq('<', commaSep($.type_parameter), '>'),
    type_parameter: $ => seq(optional('...'), field('name', $.type_identifier), optional(seq(':', $._type, repeat(seq('+', $._type))))),
    generic_arguments: $ => seq('<', commaSep($._type), '>'),
    record_declaration: $ => seq(optional($.visibility), choice(
      seq('record', field('name', $.type_identifier), optional($.generic_parameters), $._record_fields),
      seq('opaque', 'record', field('name', $.type_identifier), optional($.generic_parameters), ';'),
    )),
    _record_fields: $ => seq('{', repeat(choice($.field_declaration, ',', ';')), '}'),
    enum_declaration: $ => seq(optional($.visibility), optional('open'), 'enum', field('name', $.type_identifier), optional($.generic_parameters), '{', commaSep($.enum_variant), '}'),
    enum_variant: $ => seq(repeat($.attribute), field('name', $.identifier), optional(seq(':', $._type))),
    field_declaration: $ => seq(field('name', $.identifier), ':', $._type),
    type_declaration: $ => seq(optional($.visibility), 'type', field('name', $.type_identifier), '=', $._type),
    module_declaration: $ => prec.right(seq(optional($.visibility), optional('interface'), 'mod', field('name', choice($.identifier, $._path_keyword)), optional(choice($.block, ';')))),
    use_declaration: $ => seq(optional($.visibility), 'use', $.use_tree),
    use_tree: $ => prec.right(seq(choice($.identifier, $._path_keyword, '*', seq('{', commaSep($.use_tree), '}')), optional(seq('::', $.use_tree)), optional(seq('as', $.identifier)))),
    trait_declaration: $ => seq(optional($.visibility), 'trait', field('name', $.type_identifier), optional($.generic_parameters), $.block),
    impl_declaration: $ => seq('impl', optional($.generic_parameters), $._type, optional(seq('for', $._type)), $.block),
    interface_implementation: $ => seq('impl', 'interface', field('interface', $._qualified_type_name), 'for', field('module', $._qualified_type_name), '{', repeat(choice($.type_declaration, ';')), '}'),
    world_declaration: $ => seq(optional($.visibility), 'world', field('name', $.type_identifier), '{', repeat(choice($.world_include, $.world_import, $.world_export, ';')), '}'),
    world_include: $ => seq('include', $._qualified_type_name),
    world_import: $ => prec.right(seq('import', $._qualified_type_name, optional(seq('as', field('alias', $.identifier))), optional(seq('{', repeat($.function_declaration), '}')))),
    world_export: $ => seq('export', $.function_declaration),
    property_declaration: $ => seq(optional($.visibility), 'property', $._type, '.', field('name', $.identifier), ':', $._type, $.block),
    variable_declaration: $ => seq(optional($.visibility), choice('let', 'const'), optional('mut'), field('name', $.identifier), optional(seq(':', $._type)), '=', $._expression),
    block: $ => seq('{', repeat(choice($._item, ';')), '}'),
    if_statement: $ => prec.right(seq('if', optional(seq('let', $._pattern, '=')), $._expression, $.block, optional(seq('else', choice($.block, $.if_statement))))),
    while_statement: $ => seq('while', $._expression, $.block),
    for_statement: $ => seq('for', field('name', $.identifier), 'in', $._expression, $.block),
    return_statement: $ => prec.right(seq('return', optional($._expression))),
    jump_statement: _ => choice('break', 'continue'),
    assignment_statement: $ => prec.right(seq($._expression, choice('=', '+=', '-=', '*=', '/='), $._expression)),
    _type: $ => choice($._qualified_type_name, $.generic_type, $.reference_type, $.managed_type, $.tuple_type, $.array_type, $.dyn_type, $.callable_type, $.object_type, $.anonymous_record_type, $.lifetime),
    _qualified_type_name: $ => choice($.type_identifier, $.type_path),
    type_identifier: $ => choice($.identifier, alias(choice('char', 'string'), $.identifier)),
    type_path: $ => prec.right(seq(choice($.type_identifier, $._path_keyword), repeat1(seq('::', choice($.type_identifier, $._path_keyword))))),
    generic_type: $ => seq($._qualified_type_name, $.generic_arguments),
    reference_type: $ => seq('&', optional($.lifetime), optional('mut'), $._type),
    managed_type: $ => seq(optional($.locality), choice('gc', 'rc'), optional(seq('<', $.lifetime, '>')), $._type),
    locality: _ => seq('@', choice('local', 'shared')),
    tuple_type: $ => seq('(', commaSep($._type), ')'),
    array_type: $ => seq('[', optional($.number), ']', $._type),
    object_type: $ => choice('dynamic', seq('object', '{', repeat(seq($.field_declaration, optional(','))), optional('..'), '}')),
    anonymous_record_type: $ => seq('record', $._record_fields),
    dyn_type: $ => seq('dyn', $._qualified_type_name),
    callable_type: $ => seq(choice('fn', 'proc'), '(', commaSep($._type), ')', optional(seq('->', $._type))),
    _expression: $ => choice(
      $.identifier, $._namespace_root, $.scoped_identifier, $.number, $.string, $.character,
      $.boolean, $.binary_expression, $.unary_expression, $.cast_expression,
      $.call_expression, $.generic_call_expression, $.member_expression,
      $.index_expression, $.dereference_expression, $.tuple_expression,
      $.array_expression, $.record_expression, $.object_expression,
      $.managed_expression, $.closure_expression, $.yield_expression, $.typed_collection,
      $.match_expression, $.anonymous_record_expression,
    ),
    scoped_identifier: $ => prec(2, seq(field('scope', choice($.identifier, $.scoped_identifier, $._path_keyword)), '::', field('name', choice($.identifier, $._path_keyword)))),
    _path_keyword: $ => alias(choice('gc', 'rc', 'object', 'dynamic', 'string', 'char', 'type', 'fn', 'proc', 'gen', 'record', 'enum', 'match', 'let', 'const', 'if', 'else', 'while', 'for', 'in', 'return', 'break', 'continue', 'delete', 'yield', 'true', 'false'), $.identifier),
    _namespace_root: $ => prec(-1, alias(choice('gc', 'rc', 'object', 'dynamic'), $.identifier)),
    number: _ => token(/[0-9]+(\.[0-9]+)?([eE][+-]?[0-9]+)?(_?(usize|isize|[ui](8|16|32|64)|f(32|64)))?/),
    string: _ => token(seq('"', repeat(choice(/[^"\\\r\n]/, /\\[^\r\n]/)), optional('"'))),
    character: _ => token(seq("'", choice(/[^'\\\r\n]/, /\\[^\r\n]/), "'")),
    lifetime: _ => /'[A-Za-z][A-Za-z0-9_]*/,
    boolean: _ => choice('true', 'false'),
    binary_expression: $ => choice(...[
      [1, ['..', '..=']], [2, ['||']], [3, ['&&']],
      [4, ['==', '!=', '<', '>', '<=', '>=']], [5, ['+', '-']],
      [6, ['*', '/', '%']],
    ].map(([level, ops]) => prec.left(level, seq($._expression, field('operator', ops.length === 1 ? ops[0] : choice(...ops)), $._expression)))),
    unary_expression: $ => prec(8, seq(choice('+', '-', '!', seq('&', optional('mut')), 'delete'), $._expression)),
    cast_expression: $ => prec.left(7, seq($._expression, 'as', $._type)),
    call_expression: $ => prec(10, seq(field('function', $._expression), $.arguments)),
    generic_call_expression: $ => seq(field('function', choice($.identifier, $.scoped_identifier)), $.generic_arguments, $.arguments),
    typed_collection: $ => seq(field('type', choice($.identifier, $.scoped_identifier)), $.generic_arguments, $.array_expression),
    arguments: $ => seq('(', commaSep($._expression), ')'),
    member_expression: $ => prec(10, seq($._expression, '.', field('name', choice($.identifier, $.number)))),
    index_expression: $ => prec(10, seq($._expression, '[', commaSep($._expression), ']')),
    dereference_expression: $ => prec(10, seq($._expression, '.', '*')),
    tuple_expression: $ => seq('(', commaSep($._expression), ')'),
    array_expression: $ => seq('[', commaSep($._expression), ']'),
    record_expression: $ => seq(field('type', choice($.identifier, $.scoped_identifier)), optional($.generic_arguments), '{', repeat(seq($.field_initializer, optional(','))), '}'),
    anonymous_record_expression: $ => seq('record', '{', commaSep($.field_initializer), '}'),
    object_expression: $ => seq(choice('object', 'dynamic'), '{', repeat(seq($.field_initializer, optional(','))), '}'),
    field_initializer: $ => seq(field('name', $.identifier), ':', $._expression),
    managed_expression: $ => prec(8, seq(optional($.locality), choice('gc', 'rc'), optional($.arguments), $._expression)),
    closure_expression: $ => seq(optional('gen'), choice('fn', 'proc'), optional($.captures), $.parameters, optional(seq('->', $._type)), $.block),
    captures: $ => seq('[', commaSep(seq('&', optional('mut'), $.identifier)), ']'),
    yield_expression: $ => prec.right(seq('yield', optional('from'), $._expression)),
    match_expression: $ => seq('match', field('value', $._expression), '{', repeat(seq($.match_arm, optional(','))), '}'),
    match_arm: $ => seq(field('pattern', $._pattern), optional(seq('if', field('guard', $._expression))), '=>', field('body', choice($.block, $._expression))),
    _pattern: $ => choice($._pattern_atom, $.or_pattern),
    _pattern_atom: $ => choice($.identifier, $.variant_pattern, $.tuple_pattern, $.record_pattern, $.number, $.string, $.character, $.boolean, seq('-', $.number)),
    or_pattern: $ => seq($._pattern_atom, repeat1(seq('|', $._pattern_atom))),
    variant_pattern: $ => choice(
      seq(field('name', choice($.identifier, $.scoped_identifier)), choice(seq('(', $._pattern, ')'), $.record_pattern)),
      field('name', $.scoped_identifier),
    ),
    tuple_pattern: $ => seq('(', commaSep($._pattern), ')'),
    record_pattern: $ => seq('{', optional(choice('..', seq($.field_pattern, repeat(seq(',', $.field_pattern)), optional(seq(',', optional('..')))))), '}'),
    field_pattern: $ => seq(field('name', $.identifier), optional(seq(':', $._pattern))),
    identifier: _ => /[A-Za-z_][A-Za-z0-9_]*/,
    comment: _ => token(seq('//', /[^\r\n]*/)),
  },
});
