// Match the executable CAIE subset in caie-int-parser, including mixed case.
const ci = word => new RegExp([...word].map(c => /[a-z]/i.test(c) ? `[${c.toLowerCase()}${c.toUpperCase()}]` : c).join(''));
const list = rule => seq(rule, repeat(seq(',', rule)));
const keywords = ['DECLARE', 'CONSTANT', 'OUTPUT', 'INPUT', 'IF', 'THEN', 'ELSE', 'ENDIF', 'WHILE', 'ENDWHILE', 'REPEAT', 'UNTIL', 'FOR', 'TO', 'STEP', 'NEXT', 'CASE', 'OF', 'OTHERWISE', 'ENDCASE', 'PROCEDURE', 'ENDPROCEDURE', 'FUNCTION', 'ENDFUNCTION', 'RETURNS', 'RETURN', 'CALL', 'ARRAY', 'BYREF', 'BYVAL'];
module.exports = grammar({
  name: 'caie',
  extras: $ => [/[ \t\r]/, $.comment],
  word: $ => $.identifier,
  rules: {
    source_file: $ => repeat(choice($._statement, $._newline)),
    _newline: _ => /\n/,
    _statement: $ => choice($.declaration, $.constant_declaration, $.output_statement, $.input_statement, $.assignment_statement, $.if_statement, $.while_statement, $.repeat_statement, $.for_statement, $.case_statement, $.function_declaration, $.procedure_declaration, $.call_statement, $.return_statement),
    declaration: $ => seq($.declare_keyword, field('name', $.identifier), ':', $._type),
    constant_declaration: $ => seq($.constant_keyword, field('name', $.identifier), '=', $._expression),
    _type: $ => choice($.primitive_type, $.array_type),
    primitive_type: _ => choice(...['INTEGER', 'REAL', 'BOOLEAN', 'CHAR', 'STRING'].map(ci)),
    array_type: $ => seq($.array_keyword, '[', list($.array_bound), ']', $.of_keyword, $._type),
    array_bound: $ => seq(optional('-'), $.number, ':', optional('-'), $.number),
    output_statement: $ => seq($.output_keyword, list($._expression)),
    input_statement: $ => seq($.input_keyword, $._expression),
    assignment_statement: $ => seq($._expression, $.assignment_operator, $._expression),
    assignment_operator: _ => choice('<-', '←'),
    if_statement: $ => seq($.if_keyword, $._expression, repeat($._newline), $.then_keyword, $._newline, repeat(choice($._statement, $._newline)), optional(seq($.else_keyword, $._newline, repeat(choice($._statement, $._newline)))), $.endif_keyword),
    while_statement: $ => seq($.while_keyword, $._expression, $._newline, repeat(choice($._statement, $._newline)), $.endwhile_keyword),
    repeat_statement: $ => seq($.repeat_keyword, $._newline, repeat(choice($._statement, $._newline)), $.until_keyword, $._expression),
    for_statement: $ => prec.right(seq($.for_keyword, field('name', $.identifier), $.assignment_operator, $._expression, $.to_keyword, $._expression, optional(seq($.step_keyword, $._expression)), $._newline, repeat(choice($._statement, $._newline)), $.next_keyword, optional($.identifier))),
    case_statement: $ => seq($.case_keyword, $.of_keyword, $._expression, $._newline, repeat(choice($.case_arm, $._newline)), optional(seq($.otherwise_keyword, optional(':'), repeat(choice($._statement, $._newline)))), $.endcase_keyword),
    case_arm: $ => prec.right(seq($._expression, optional(seq($.to_keyword, $._expression)), ':', repeat(choice($._statement, $._newline)))),
    function_declaration: $ => seq($.function_keyword, field('name', $.identifier), $.parameters, $.returns_keyword, $._type, $._newline, repeat(choice($._statement, $._newline)), $.endfunction_keyword),
    procedure_declaration: $ => seq($.procedure_keyword, field('name', $.identifier), $.parameters, $._newline, repeat(choice($._statement, $._newline)), $.endprocedure_keyword),
    parameters: $ => seq('(', optional(list($.parameter)), ')'),
    parameter: $ => seq(optional(choice($.byref_keyword, $.byval_keyword)), field('name', $.identifier), ':', $._type),
    call_statement: $ => seq($.call_keyword, field('name', $.identifier), $.arguments),
    return_statement: $ => seq($.return_keyword, $._expression),
    _expression: $ => choice($.identifier, $.number, $.string, $.character, $.boolean, $.binary_expression, $.unary_expression, $.parenthesized_expression, $.call_expression, $.index_expression),
    call_expression: $ => prec(9, seq(field('function', $.identifier), $.arguments)),
    arguments: $ => seq('(', optional(list($._expression)), ')'),
    index_expression: $ => prec(9, seq($._expression, '[', list($._expression), ']')),
    parenthesized_expression: $ => seq('(', $._expression, ')'),
    binary_expression: $ => choice(...[
      [1, [ci('OR')]], [2, [ci('AND')]], [3, ['=', '<>', '<', '>', '<=', '>=']],
      [4, ['&']], [5, ['+', '-']], [6, ['*', '/', ci('DIV'), ci('MOD')]],
    ].map(([level, ops]) => prec.left(level, seq($._expression, field('operator', alias(ops.length === 1 ? ops[0] : choice(...ops), $.operator)), $._expression)))),
    unary_expression: $ => prec(7, seq(field('operator', alias(choice('+', '-', ci('NOT')), $.operator)), $._expression)),
    number: _ => /[0-9]+(\.[0-9]+)?/,
    // A backslash is literal in CAIE. Unterminated strings end at the newline.
    string: _ => token(seq('"', /[^"\r\n]*/, optional('"'))),
    character: _ => token(seq("'", /[^'\r\n]?/, optional("'"))),
    boolean: _ => choice(ci('TRUE'), ci('FALSE')),
    identifier: _ => /[A-Za-z][A-Za-z0-9_]*/,
    comment: _ => token(seq('//', /[^\r\n]*/)),
    ...Object.fromEntries(keywords.map(word => [`${word.toLowerCase()}_keyword`, () => token(prec(1, ci(word)))])),
  },
});
